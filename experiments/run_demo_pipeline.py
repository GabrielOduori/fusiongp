        epa_holdout_mode = os.getenv("EPA_HOLDOUT_MODE", "random").strip().lower()
        if epa_holdout_mode == "station":
            split_strategy = "epa_station_holdout"
            holdout_fraction = float(os.getenv("EPA_HOLDOUT_FRACTION", "0.25"))
            holdout_grid_ids = [
                grid_id.strip()
                for grid_id in os.getenv("EPA_HOLDOUT_GRID_IDS", "").split(",")
                if grid_id.strip()
            ]
            train_ratio = max(0.0, 1.0 - 0.15 - holdout_fraction)

def export_uq_dataset(
    data,
    output_path: Path,
    scalers,
    covariate_columns=None,
    lur_source_column: str = "predicted_no2",
    data_path_for_lur: Path | None = None,
    add_lur_as_source: bool = False,
):
    """
    Export FusionData into a long-form CSV for external UQ.

    Columns: latitude, longitude, timestamp, value, source, grid_id, [covariates...], [lur_no2]
    Optionally appends LUR rows as a separate source.
    """
    # UQ export: keep long-form rows so downstream pipelines can filter by source.
    rows = []
    covariate_columns = covariate_columns or []

    for source, mask in data.source_masks.items():
        if mask.sum() == 0:
            continue

        vals = data.observations[source].copy()
        if scalers is not None and getattr(scalers, "normalize_targets", False) and source in scalers.target_std:
            vals = vals * scalers.target_std[source] + scalers.target_mean[source]

        coords = data.coords[mask]
        timestamps = data.timestamps[mask]
        grid_ids = data.grid_ids[mask] if data.grid_ids is not None else [float("nan")] * len(timestamps)

        df = pd.DataFrame({
            "latitude": coords[:, 0],
            "longitude": coords[:, 1],
            "timestamp": timestamps,
            "grid_id": grid_ids,
            "value": vals[mask],
            "source": source,
        })

        if getattr(data, "covariates", None) is not None and len(covariate_columns) == data.covariates.shape[1]:
            cov = data.covariates[mask]
            for i, col in enumerate(covariate_columns):
                df[col] = cov[:, i]

        rows.append(df)

    if not rows:
        return

    out = pd.concat(rows, ignore_index=True)

    if data_path_for_lur is not None and "grid_id" in out.columns:
        try:
            df_lur = pd.read_csv(data_path_for_lur, usecols=["grid_id", lur_source_column])
            df_lur = df_lur.dropna(subset=["grid_id"]).drop_duplicates("grid_id")
            out = out.merge(
                df_lur.rename(columns={lur_source_column: "lur_no2"}),
                on="grid_id",
                how="left",
            )
        except (FileNotFoundError, KeyError, ValueError, pd.errors.ParserError) as exc:
            logger.warning("Could not add LUR source column from %s: %s", data_path_for_lur, exc)
            out["lur_no2"] = float("nan")

        if add_lur_as_source and "lur_no2" in out.columns:
            lur_rows = out[out["lur_no2"].notna()].copy()
            lur_rows["value"] = lur_rows["lur_no2"]
            lur_rows["source"] = "lur"
            out = pd.concat([out, lur_rows], ignore_index=True)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(output_path, index=False)


def _set_source_missing(data, source_name: str):
    """Return data with one source masked out in-place."""
    if source_name not in data.observations:
        return data
    obs = data.observations[source_name].copy()
    obs[:] = np.nan
    data.observations[source_name] = obs
    data.source_masks[source_name] = ~np.isnan(obs)
    return data


def _keep_random_source_fraction(data, source_name: str, keep_frac: float, seed: int = 42):
    """Keep a deterministic fraction of valid observations for a source in-place."""
    if source_name not in data.observations:
        return data

    obs = data.observations[source_name].copy()
    mask = data.source_masks[source_name].copy()
    idx = np.where(mask)[0]
    if len(idx) == 0:
        return data

    rng = np.random.default_rng(seed)
    n_keep = max(1, int(len(idx) * keep_frac))
    keep_idx = rng.choice(idx, size=n_keep, replace=False)
    drop_idx = np.setdiff1d(idx, keep_idx)
    obs[drop_idx] = np.nan
    data.observations[source_name] = obs
    data.source_masks[source_name] = ~np.isnan(obs)
    return data


def _fit_source_to_epa_calibration(train_data, source_name: str, min_points: int = 10) -> dict:
    """
    Fit EPA = slope * source + intercept on colocated raw training observations.

    This mirrors the gam_ssm_lur calibration direction: dense source values are
    converted to surface-equivalent EPA NO2 before model fitting.
    """
    epa_mask = train_data.source_masks.get("epa")
    source_mask = train_data.source_masks.get(source_name)
    if epa_mask is None or source_mask is None:
        return {
            "source": source_name,
            "slope": 1.0,
            "intercept": 0.0,
            "n_points": 0,
            "r2": None,
            "applied": False,
            "reason": "missing source",
        }

    coloc_mask = epa_mask & source_mask
    epa_vals = train_data.observations["epa"][coloc_mask]
    source_vals = train_data.observations[source_name][coloc_mask]
    valid = np.isfinite(epa_vals) & np.isfinite(source_vals)
    epa_vals = epa_vals[valid]
    source_vals = source_vals[valid]

    if len(epa_vals) < min_points:
        return {
            "source": source_name,
            "slope": 1.0,
            "intercept": 0.0,
            "n_points": int(len(epa_vals)),
            "r2": None,
            "applied": False,
            "reason": f"fewer than {min_points} colocated training points",
        }

    design = np.vstack([source_vals, np.ones_like(source_vals)]).T
    slope, intercept = np.linalg.lstsq(design, epa_vals, rcond=None)[0]
    fitted = slope * source_vals + intercept
    ss_res = float(np.sum((epa_vals - fitted) ** 2))
    ss_tot = float(np.sum((epa_vals - epa_vals.mean()) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else None

    return {
        "source": source_name,
        "slope": float(slope),
        "intercept": float(intercept),
        "n_points": int(len(epa_vals)),
        "r2": float(r2) if r2 is not None and np.isfinite(r2) else None,
        "source_mean_before": float(np.nanmean(train_data.observations[source_name][source_mask])),
        "epa_mean": float(np.nanmean(train_data.observations["epa"][epa_mask])),
        "applied": True,
        "reason": "ok",
    }


def _apply_source_to_epa_calibration(data, calibration: dict):
    """Apply an EPA = slope * source + intercept calibration to one split."""
    source_name = calibration["source"]
    if not calibration.get("applied") or source_name not in data.observations:
        return data

    mask = data.source_masks[source_name]
    values = data.observations[source_name].copy()
    values[mask] = calibration["slope"] * values[mask] + calibration["intercept"]
    data.observations[source_name] = values
    data.source_masks[source_name] = np.isfinite(values)
    return data


def _thin_repeated_source_observations(
    data,
    source_name: str,
    value_decimals: int = 3,
    max_per_group: int = 1,
) -> dict:
    """
    Keep only an effective set of repeated source observations per day/value.

    TROPOMI values projected onto a fine LUR grid often repeat across many grid
    cells. Those rows are useful for plotting on the fine grid, but they should
    not all contribute independent likelihood terms. This masks duplicates while
    leaving all other sources and coordinates untouched.
    """
    if source_name not in data.observations:
        return {
            "source": source_name,
            "method": "none",
            "before": 0,
            "after": 0,
            "removed": 0,
            "reason": "missing source",
        }

    mask = data.source_masks[source_name].copy()
    before = int(mask.sum())
    if before == 0:
        return {
            "source": source_name,
            "method": "none",
            "before": 0,
            "after": 0,
            "removed": 0,
            "reason": "no valid observations",
        }

    max_per_group = max(1, int(max_per_group))
    values = data.observations[source_name]
    valid_idx = np.where(mask)[0]

    raw_ts = getattr(data, "raw_timestamps", None)
    if raw_ts is not None:
        date_key = pd.to_datetime(raw_ts[valid_idx], errors="coerce").date.astype(str)
    else:
        date_key = np.round(data.timestamps[valid_idx], 8).astype(str)

    groups = pd.DataFrame({
        "idx": valid_idx,
        "date_key": date_key,
        "value_key": np.round(values[valid_idx], value_decimals),
    }).sort_values(["date_key", "value_key", "idx"])

    keep_idx = groups[
        groups.groupby(["date_key", "value_key"], sort=False).cumcount() < max_per_group
    ]["idx"].to_numpy(dtype=int)

    new_mask = np.zeros_like(mask, dtype=bool)
    new_mask[keep_idx] = True
    data.source_masks[source_name] = new_mask

    obs = values.copy()
    obs[~new_mask] = np.nan
    data.observations[source_name] = obs

    after = int(new_mask.sum())
    n_groups = int(groups.groupby(["date_key", "value_key"], sort=False).ngroups)
    return {
        "source": source_name,
        "method": "date_plus_rounded_value",
        "value_decimals": int(value_decimals),
        "max_per_group": int(max_per_group),
        "before": before,
        "after": after,
        "removed": before - after,
        "effective_groups": n_groups,
    }


def _concat_fusion_data(parts):
    """Concatenate FusionData objects that share the same source schema."""
    from src.data.loader import FusionData

    parts = [part for part in parts if part is not None and part.n_observations > 0]
    if not parts:
        raise ValueError("No FusionData parts to concatenate")

    sources = parts[0].observations.keys()
    covariates = None
    if getattr(parts[0], "covariates", None) is not None:
        covariates = np.concatenate([part.covariates for part in parts], axis=0)

    return FusionData(
        coords=np.concatenate([part.coords for part in parts], axis=0),
        timestamps=np.concatenate([part.timestamps for part in parts], axis=0),
        observations={
            source: np.concatenate([part.observations[source] for part in parts], axis=0)
            for source in sources
        },
        source_masks={
            source: np.concatenate([part.source_masks[source] for part in parts], axis=0)
            for source in sources
        },
        grid_ids=np.concatenate([part.grid_ids for part in parts], axis=0),
        raw_timestamps=np.concatenate([part.raw_timestamps for part in parts], axis=0),
        covariates=covariates,
        metadata={**parts[0].metadata, "concat_size": sum(part.n_observations for part in parts)},
    )


def compute_upwind_traffic(
    df: pd.DataFrame,
    traffic: np.ndarray,
    n_sectors: int = 8,
    max_dist_km: float = 3.0,
    decay_power: float = 2.0,
    lat_col: str = "latitude",
    lon_col: str = "longitude",
) -> np.ndarray:
    """
    For each grid cell and each wind sector i, compute the IDW-weighted sum of
    traffic volumes from cells that lie upwind (in the direction FROM which
    sector i wind blows).

    Wind sector i = wind arriving FROM direction i * (360/n_sectors) degrees
    clockwise from North.  Upwind cells for sector i are those located in that
    direction from the target cell, within max_dist_km.

    Returns array of shape (n_rows, n_sectors).
    """
    # Deduplicate to unique grid cells for efficient O(n_cells²) computation
    coords_df = df[[lat_col, lon_col]].copy()
    unique_coords = coords_df.drop_duplicates().reset_index(drop=True)
    n_unique = len(unique_coords)

    unique_keys = list(zip(unique_coords[lat_col], unique_coords[lon_col]))
    key_to_idx = {k: i for i, k in enumerate(unique_keys)}
    row_to_cell = np.array([
        key_to_idx[(lat, lon)]
        for lat, lon in zip(df[lat_col], df[lon_col])
    ])

    # Assign traffic value to each unique cell (take mean across rows — should
    # be constant since traffic is a static grid attribute)
    cell_traffic = np.zeros(n_unique)
    for row_i, cell_i in enumerate(row_to_cell):
        cell_traffic[cell_i] = traffic[row_i]

    # Local Cartesian coordinates (km), centred on domain mean
    lat_arr = unique_coords[lat_col].to_numpy()
    lon_arr = unique_coords[lon_col].to_numpy()
    lat_mean = lat_arr.mean()
    km_per_deg_lat = 111.0
    km_per_deg_lon = 111.0 * np.cos(np.radians(lat_mean))

    y = (lat_arr - lat_mean) * km_per_deg_lat   # North (km)
    x = (lon_arr - lon_arr.mean()) * km_per_deg_lon  # East (km)

    # Pairwise displacement: dx[i,j] = x[j]-x[i]  (vector from cell i to j)
    dx = x[None, :] - x[:, None]   # (n_unique, n_unique)
    dy = y[None, :] - y[:, None]
    dist_km = np.sqrt(dx ** 2 + dy ** 2)

    # Bearing of vector i→j: degrees clockwise from North
    bearing = np.degrees(np.arctan2(dx, dy)) % 360  # atan2(East, North)
    del dx, dy   # free pairwise displacement arrays (~56 MB) before sector loop

    sector_size = 360.0 / n_sectors
    half_width = sector_size / 2.0

    cell_upwind = np.zeros((n_unique, n_sectors))
    for s in range(n_sectors):
        center = s * sector_size
        ang_diff = (bearing - center + 180) % 360 - 180   # in [-180, 180]
        in_sector = np.abs(ang_diff) <= half_width
        in_range = (dist_km > 1e-9) & (dist_km <= max_dist_km)
        valid = in_sector & in_range
        weights = np.where(valid, 1.0 / np.maximum(dist_km, 1e-9) ** decay_power, 0.0)
        cell_upwind[:, s] = (weights * cell_traffic[None, :]).sum(axis=1)

    del dist_km, bearing   # free pairwise matrices before returning
    tqdm.write(
        f"Upwind traffic: {n_unique} unique cells, "
        f"max_dist={max_dist_km} km, sectors={n_sectors}"
    )
    return cell_upwind[row_to_cell]   # (n_rows, n_sectors)


def add_wind_weighted_covariates(df: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    """
    Create wind-frequency weighted covariates.

    For each wind sector i the feature captures how much traffic-generated
    pollution is expected to arrive at each cell:

        traffic_wind_i  = upwind_traffic_i × local_wind_freq_i
        wind_speed_w_i  = local_wind_speed_i × local_wind_freq_i

    upwind_traffic_i is the IDW-weighted sum of traffic counter readings from
    cells upwind (in sector i direction) within max_dist_km.  Cells without
    counters (traffic_volume == 0) contribute nothing to the upwind sum —
    only verified counter readings are used.

    Required columns:
      wind_sector_0_freq ... wind_sector_7_freq
      wind_sector_0_mean_speed ... wind_sector_7_mean_speed
      traffic_volume
    """
    wind_freq_cols = [f"wind_sector_{i}_freq" for i in range(8)]
    wind_speed_cols = [f"wind_sector_{i}_mean_speed" for i in range(8)]
    required = wind_freq_cols + wind_speed_cols + ["traffic_volume"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns for wind-weighted features: {missing}")

    freq = df[wind_freq_cols].fillna(0.0).to_numpy()
    speed = df[wind_speed_cols].fillna(0.0).to_numpy()

    # Counter cells have real values; counter-free cells get a small floor
    # so they don't produce exact zeros but contribute negligibly to upwind sums
    traffic = df["traffic_volume"].fillna(0.0).to_numpy(dtype=float)
    traffic = np.where(traffic == 0.0, 1.0, traffic)

    # Aggregate upwind counter traffic for each sector (wind transport)
    upwind = compute_upwind_traffic(df, traffic)

    # Step 3: weight by local wind frequency
    for i in range(8):
        df[f"traffic_wind_{i}"] = upwind[:, i] * freq[:, i]
        df[f"wind_speed_w_{i}"] = speed[:, i] * freq[:, i]

    covariate_columns = (
        [f"traffic_wind_{i}" for i in range(8)] +
        [f"wind_speed_w_{i}" for i in range(8)]
    )
    return df, covariate_columns



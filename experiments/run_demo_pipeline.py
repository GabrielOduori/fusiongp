        def format_comparison(title, base_metrics, fused_metrics):
            def pct_improve(base, fused):
                if np.isnan(base) or base == 0:
                    return "n/a"
                return f"{(1.0 - fused / base) * 100:>6.1f}%"

            lines = []
            lines.append("=" * 70)

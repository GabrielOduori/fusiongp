def _shift_predictions(predictions: Predictions, mean_shift: float | np.ndarray) -> Predictions:
    """Shift prediction means and intervals by a constant offset."""
    mean_shift = np.asarray(mean_shift, dtype=float)
    if not np.all(np.isfinite(mean_shift)) or float(np.max(np.abs(mean_shift))) < 1e-12:
        return predictions
    return Predictions(
        mean=predictions.mean + mean_shift,
        std=predictions.std,
        lower_ci={level: values + mean_shift for level, values in predictions.lower_ci.items()},
        upper_ci={level: values + mean_shift for level, values in predictions.upper_ci.items()},
        coords=predictions.coords,
        timestamps=predictions.timestamps,
        grid_ids=predictions.grid_ids,
    )


def _idw_mean_shift(
    coords: np.ndarray,
    anchor_coords: np.ndarray,
    anchor_shifts: np.ndarray,
    power: float = 2.0,
) -> np.ndarray:
    """Interpolate EPA residual shifts from station anchors with inverse distance weights."""
    if len(anchor_coords) == 0:
        return np.zeros(len(coords), dtype=float)

    coords = np.asarray(coords, dtype=float)
    anchor_coords = np.asarray(anchor_coords, dtype=float)
    anchor_shifts = np.asarray(anchor_shifts, dtype=float)
    lat_scale = 111.0
    lon_scale = 111.0 * np.cos(np.deg2rad(np.nanmean(anchor_coords[:, 0])))
    delta_lat = (coords[:, None, 0] - anchor_coords[None, :, 0]) * lat_scale
    delta_lon = (coords[:, None, 1] - anchor_coords[None, :, 1]) * lon_scale
    dist_km = np.sqrt(delta_lat**2 + delta_lon**2)
    exact = dist_km < 1e-6
    weights = 1.0 / np.maximum(dist_km, 1e-6) ** power
    shifts = np.sum(weights * anchor_shifts[None, :], axis=1) / np.sum(weights, axis=1)
    exact_rows = np.where(exact.any(axis=1))[0]
    if len(exact_rows):
        shifts[exact_rows] = anchor_shifts[np.argmax(exact[exact_rows], axis=1)]
    return shifts


def _bias_shifts_for_coords(coords: np.ndarray, bias_correction: dict) -> np.ndarray:
    """Return per-location mean shifts for a saved bias-correction configuration."""
    method = bias_correction.get("method", "global")
    if method == "spatial_idw":
        anchors = bias_correction.get("anchors", [])
        anchor_coords = np.array([[a["latitude"], a["longitude"]] for a in anchors], dtype=float)
        anchor_shifts = np.array([a["mean_shift"] for a in anchors], dtype=float)
        return _idw_mean_shift(
            coords,
            anchor_coords,
            anchor_shifts,
            power=float(bias_correction.get("idw_power", 2.0)),
        )
    return np.full(len(coords), float(bias_correction.get("mean_shift", 0.0)), dtype=float)


def _estimate_epa_train_bias_correction(
    predictor: Predictor,
    train_data,
    scalers,
    method: str = "global",
) -> dict[str, float | int | str]:
    """Estimate a constant mean correction from EPA training residuals only."""
    train_mask = train_data.source_masks.get("epa")
    if train_mask is None or not np.any(train_mask):
        return {
            "source": "epa_train",
            "method": method,
            "n_points": 0,
            "bias_before": 0.0,
            "mean_shift": 0.0,
            "reason": "no_epa_training_points",
        }

    train_predictions = predictor.predict(train_data, verbose=False, task="epa")
    y_train = train_data.observations["epa"][train_mask]
    if getattr(scalers, "normalize_targets", False) and "epa" in scalers.target_std:
        y_train = y_train * scalers.target_std["epa"] + scalers.target_mean["epa"]

    pred_train = train_predictions.mean[train_mask]
    valid = np.isfinite(y_train) & np.isfinite(pred_train)
    if not np.any(valid):
        return {
            "source": "epa_train",
            "method": method,
            "n_points": 0,
            "bias_before": 0.0,
            "mean_shift": 0.0,
            "reason": "no_finite_epa_training_residuals",
        }

    bias_before = float(np.mean(pred_train[valid] - y_train[valid]))
    if method == "spatial_idw":
        coords_train = train_predictions.coords[train_mask][valid]
        grid_ids = np.asarray(train_data.grid_ids[train_mask])[valid]
        residual_df = pd.DataFrame({
            "grid_id": grid_ids,
            "latitude": coords_train[:, 0],
            "longitude": coords_train[:, 1],
            "shift": y_train[valid] - pred_train[valid],
        })
        anchors_df = (
            residual_df
            .groupby("grid_id", as_index=False)
            .agg(
                latitude=("latitude", "mean"),
                longitude=("longitude", "mean"),
                mean_shift=("shift", "mean"),
                n=("shift", "size"),
            )
        )
        anchors = [
            {
                "grid_id": str(row.grid_id),
                "latitude": float(row.latitude),
                "longitude": float(row.longitude),
                "mean_shift": float(row.mean_shift),
                "n": int(row.n),
            }
            for row in anchors_df.itertuples(index=False)
        ]
        return {
            "source": "epa_train_spatial",
            "method": "spatial_idw",
            "idw_power": 2.0,
            "n_points": int(np.sum(valid)),
            "n_anchors": int(len(anchors)),
            "bias_before": bias_before,
            "mean_shift": float(np.mean(anchors_df["mean_shift"])),
            "reason": "ok",
            "anchors": anchors,
        }

    return {
        "source": "epa_train",
        "method": "global",
        "n_points": int(np.sum(valid)),
        "bias_before": bias_before,
        "mean_shift": -bias_before,
        "reason": "ok",
    }


def _numeric_days_from_timestamp_column(timestamp_col: pd.Series) -> np.ndarray:
    """Match DataLoader's timestamp conversion: days since first timestamp."""
    dt = pd.to_datetime(timestamp_col, errors="coerce")
    if dt.notna().any():
        return ((dt - dt.min()).dt.total_seconds() / 86400.0).to_numpy()
    return pd.to_numeric(timestamp_col, errors="coerce").to_numpy(dtype=float)


def export_dense_fusion_grid_maps(
    predictor: Predictor,
    df: pd.DataFrame,
    grid_df: pd.DataFrame,
    covariate_columns: list[str],
    selected_day_indices: list[int],
    output_dir: Path,
    scalers,
    bias_correction: dict | None = None,
) -> list[Path]:
    """
    Predict FusionSVGP posterior mean/std on every LUR grid cell for selected days.

    The old map export used sparse test-set predictions. These dense surfaces give
    plotting code the same full-grid contract as LUR and GPKF maps.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    days = np.array(sorted(np.unique(_numeric_days_from_timestamp_column(df["timestamp"]))))
    if len(days) == 0:
        return []

    df_day = df.copy()
    df_day["_numeric_day"] = _numeric_days_from_timestamp_column(df_day["timestamp"])
    grid_base = grid_df[["grid_id", "latitude", "longitude"]].drop_duplicates("grid_id").copy()

    covariate_fill = {
        col: float(scalers.covariate_mean[i])
        for i, col in enumerate(covariate_columns)
        if i < len(getattr(scalers, "covariate_mean", []))
    }
    written = []

    for day_idx in selected_day_indices:
        pos = day_idx - 1
        if pos < 0 or pos >= len(days):
            tqdm.write(f"Skipping dense fusion grid day {day_idx}: only {len(days)} unique days available")
            continue

        day_val = days[pos]
        out_path = output_dir / f"fusion_grid_day_{day_idx:02d}.csv"
        reuse_existing = os.getenv("REUSE_DENSE_FUSION_MAPS", "0").lower() in {"1", "true", "yes"}
        if reuse_existing and out_path.exists():
            try:
                existing_cols = pd.read_csv(out_path, nrows=0).columns
                if "n_obs" in existing_cols:
                    written.append(out_path)
                    continue
            except (OSError, pd.errors.ParserError):
                pass

        day_df = df_day[np.isclose(df_day["_numeric_day"], day_val)]
        n_epa_obs = int(day_df["epa_no2"].notna().sum()) if "epa_no2" in day_df.columns else 0
        n_sat_obs = int(day_df["satellite_no2"].notna().sum()) if "satellite_no2" in day_df.columns else 0
        day_rows = (
            day_df
            [["grid_id", *covariate_columns]]
            .drop_duplicates("grid_id")
        )
        query = grid_base.merge(day_rows, on="grid_id", how="left")
        for col in covariate_columns:
            fill_value = covariate_fill.get(col, float(query[col].median(skipna=True)))
            query[col] = query[col].fillna(fill_value)

        preds = predictor.predict_locations(
            coords=query[["latitude", "longitude"]].to_numpy(),
            timestamps=np.full(len(query), day_val, dtype=float),
            covariates=query[covariate_columns].to_numpy() if covariate_columns else None,
            normalized=False,
            verbose=False,
            task="epa",
        )
        if bias_correction is not None:
            preds = _shift_predictions(preds, _bias_shifts_for_coords(preds.coords, bias_correction))

        pd.DataFrame({
            "grid_id": query["grid_id"].to_numpy(),
            "latitude": query["latitude"].to_numpy(),
            "longitude": query["longitude"].to_numpy(),
            "mean_ug_m3": preds.mean,
            "std_ug_m3": preds.std,
            "n_obs": n_epa_obs,
            "n_epa_obs": n_epa_obs,
            "n_sat_obs": n_sat_obs,
            "day": day_val,
        }).to_csv(out_path, index=False)
        written.append(out_path)

    return written


def save_leaflet_map(
    path: Path,
    coords: np.ndarray,
    values: np.ndarray,
    title: str,
    max_points: int = 30000,
) -> None:
    """
    Save an interactive Leaflet map (HTML) with colored circle markers.
    """
    if folium is None or _linear_colormap is None:
        return

    if len(coords) == 0:
        return

    # Downsample for performance
    if len(coords) > max_points:
        idx = np.random.default_rng(42).choice(len(coords), size=max_points, replace=False)
        coords = coords[idx]
        values = values[idx]

    center = [float(np.nanmean(coords[:, 0])), float(np.nanmean(coords[:, 1]))]
    m = folium.Map(location=center, zoom_start=11, tiles="cartodbpositron")

    finite = values[np.isfinite(values)]
    if len(finite) == 0:
        return  # nothing to plot
    vmin = float(finite.min())
    vmax = float(finite.max())
    if vmax <= vmin:
        vmax = vmin + 1.0
    cmap = _linear_colormap.viridis.scale(vmin, vmax)
    cmap.caption = title
    cmap.add_to(m)

    for (lat, lon), val in zip(coords, values):
        if not np.isfinite(val):
            continue
        color = cmap(val)
        folium.CircleMarker(
            location=[float(lat), float(lon)],
            radius=2,
            color=color,
            fill=True,
            fill_opacity=0.7,
            opacity=0.7,
            weight=0,
        ).add_to(m)

    m.save(path)


